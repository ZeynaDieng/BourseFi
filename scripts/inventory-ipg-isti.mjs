async function generateInventoryReport() {
  console.log('=== INVENTAIRE EXHAUSTIF DU CATALOGUE IPG-ISTI (SOURCE BROCHURE) ===\n')

  console.log(`TOTAL D ENTRÉES DÉTECTÉES : ${ipgBrochureCatalogue.length}\n`)

  const byDept = {}
  const byLevel = {}
  const byCat = {}

  ipgBrochureCatalogue.forEach((p, index) => {
    byDept[p.dept] = (byDept[p.dept] || 0) + 1
    byLevel[p.level] = (byLevel[p.level] || 0) + 1
    byCat[p.cat] = (byCat[p.cat] || 0) + 1
  })

  console.log('TOTAL PAR DÉPARTEMENT :')
  console.table(byDept)

  console.log('\nTOTAL PAR NIVEAU :')
  console.table(byLevel)

  console.log('\nTOTAL PAR CATÉGORIE :')
  console.table(byCat)

  console.log('\nTABLEAU D INVENTAIRE DÉTAILLÉ :')
  console.table(
    ipgBrochureCatalogue.map((p, i) => ({
      ID: i + 1,
      Département: p.dept,
      Catégorie: p.cat,
      Diplôme: p.diploma,
      Niveau: p.level,
      'Nom exact': p.title,
      Durée: p.duration,
      Admission: p.admission,
      'Coût annuel': p.normalFee ? `${p.normalFee.toLocaleString()} FCFA` : 'À confirmer',
      Inscription: p.inscription ? `${p.inscription.toLocaleString()} FCFA` : 'À confirmer',
      Source: p.source,
      Statut: p.status,
    })),
  )
}

